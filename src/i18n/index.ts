export function localizeDigits(
  value: string | number,
  language: AppLanguage,
  devanagari: boolean,
): string {
  const input = String(value);
  return language === 'hi' && devanagari
    ? input.replace(/[0-9]/g, (digit) => '०१२३४५६७८९'[Number(digit)] ?? digit)
    : input;
}

